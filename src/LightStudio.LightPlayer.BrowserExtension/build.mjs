function integrityOf(data) {
    return 'sha512-' + crypto.createHash('sha512').update(data).digest('base64');
}

// The release tarball from the cache, or from the npm registry when the cache has no matching copy.
async function vendorArchive(library) {
    const file = path.join(vendorCache, `${library.name}-${library.version}.tgz`);
    if (fs.existsSync(file)) {
        const cached = fs.readFileSync(file);
        if (integrityOf(cached) === library.integrity) {
            return cached;
        }
    }
    const url = `https://registry.npmjs.org/${library.name}/-/${library.name}-${library.version}.tgz`;
    const response = await fetch(url);
    if (!response.ok) {
        throw new Error(`Downloading ${url} failed with HTTP ${response.status}.`);
    }
    const data = Buffer.from(await response.arrayBuffer());
    const actual = integrityOf(data);
    if (actual !== library.integrity) {
        throw new Error(`${url} has integrity ${actual}, expected ${library.integrity}.`);
    }
    fs.mkdirSync(vendorCache, { recursive: true });
    fs.writeFileSync(file, data);
    return data;
}

// Regular files of a tar archive whose path below the top folder is in `wanted`.
function untar(archive, wanted) {
    const found = new Map();
    let longName = null;
    for (let offset = 0; offset + 512 <= archive.length;) {
        const header = archive.subarray(offset, offset + 512);
        if (header.every((byte) => byte === 0)) {
            break;
        }
        const field = (start, length) => {
            const raw = header.subarray(start, start + length);
            const end = raw.indexOf(0);
            return raw.subarray(0, end < 0 ? length : end).toString('utf8');
        };
        const size = parseInt(field(124, 12).trim() || '0', 8);
        const type = header[156] === 0 ? '0' : String.fromCharCode(header[156]);
        const body = archive.subarray(offset + 512, offset + 512 + size);
        const prefix = field(345, 155);
        const name = longName ?? (prefix ? `${prefix}/${field(0, 100)}` : field(0, 100));
        longName = null;
        if (type === 'x') {
            longName = /\d+ path=([^\n]*)\n/.exec(body.toString('utf8'))?.[1] ?? null;
        } else if (type === 'L') {
            longName = body.toString('utf8').replace(/\0[\s\S]*$/, '');
        } else if (type === '0') {
            const relative = name.slice(name.indexOf('/') + 1);
            if (wanted.has(relative)) {
                found.set(relative, Buffer.from(body));
            }
        }
        offset += 512 + Math.ceil(size / 512) * 512;
    }
    return found;
}

async function vendorFiles() {
    const files = new Map();
    for (const library of vendored) {
        const archive = zlib.gunzipSync(await vendorArchive(library));
        const found = untar(archive, new Set(Object.keys(library.files)));
        for (const [from, to] of Object.entries(library.files)) {
            if (!found.has(from)) {
                throw new Error(`${library.name} ${library.version} has no ${from}.`);
            }
            files.set(`vendor/${to}`, found.get(from));
        }
    }
    return files;
}

// The page-world takeover script: the remote media classes and the shim in one closure whose
// `globalThis` is a private object, so nothing of the extension becomes a global of the page.
// The gate stops it before anything else runs in a frame that is not armed.
function takeoverBundle() {
    const part = (file) => `// ---- ${file} ----\n${fs.readFileSync(path.join(source, file), 'utf8')}`;
    return [
        '// Generated by build.mjs from takeover/gate.js, remote/ and takeover/shim.js.',
        '(function () {',
        "'use strict';",
        'const globalThis = { LightPlayerRemoteConfig: { nativeEvents: true } };',
        part('takeover/gate.js'),
        'if (!globalThis.LightPlayerTakeover) return;',
        ...['remote/core.js', 'remote/type-support.js', 'remote/media-source.js', 'remote/media-element.js', 'remote/session.js', 'takeover/shim.js'].map(part),
        '})();',
        '',
    ].join('\n');
}

function copyTree(from, to) {
    fs.mkdirSync(to, { recursive: true });
    for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
        if ((from === source && excluded.has(entry.name)) || entry.name === 'README.md') {
            continue;
        }
        const target = path.join(to, entry.name);
        if (entry.isDirectory()) {
            copyTree(path.join(from, entry.name), target);
        } else {
            fs.copyFileSync(path.join(from, entry.name), target);
        }
    }
}

// Relative paths of the files below `folder`, sorted, with `/` separators.
function listFiles(folder, prefix = '') {
    const files = [];
    for (const entry of fs.readdirSync(path.join(folder, prefix), { withFileTypes: true })) {
        const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
        if (entry.isDirectory()) {
            files.push(...listFiles(folder, relative));
        } else {
            files.push(relative);
        }
    }
    return files.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

const crcTable = Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k++) {
        c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    return c >>> 0;
});

function crc32(data) {
    let crc = 0xffffffff;
    for (const byte of data) {
        crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8);
    }
    return (crc ^ 0xffffffff) >>> 0;
}

// A ZIP archive of every file below `folder`, with the manifest at its root. The contents depend
// only on the files: entries are sorted, every entry has the same timestamp (1980-01-01 00:00),
// and there are no directory entries or extra fields.
function zipFolder(folder) {
    const dosTime = 0;
    const dosDate = (0 << 9) | (1 << 5) | 1;
    const locals = [];
    const centrals = [];
    let offset = 0;
    for (const file of listFiles(folder)) {
        const name = Buffer.from(file, 'utf8');
        const data = fs.readFileSync(path.join(folder, file));
        const deflated = zlib.deflateRawSync(data, { level: 9 });
        const stored = deflated.length >= data.length;
        const body = stored ? data : deflated;
        const crc = crc32(data);
        const local = Buffer.alloc(30);
        local.writeUInt32LE(0x04034b50, 0);
        local.writeUInt16LE(20, 4);
        local.writeUInt16LE(0, 6);
        local.writeUInt16LE(stored ? 0 : 8, 8);
        local.writeUInt16LE(dosTime, 10);
        local.writeUInt16LE(dosDate, 12);
        local.writeUInt32LE(crc, 14);
        local.writeUInt32LE(body.length, 18);
        local.writeUInt32LE(data.length, 22);
        local.writeUInt16LE(name.length, 26);
        local.writeUInt16LE(0, 28);
        const central = Buffer.alloc(46);
        central.writeUInt32LE(0x02014b50, 0);
        central.writeUInt16LE(20, 4);
        local.copy(central, 6, 4, 30);
        central.writeUInt16LE(0, 32);
        central.writeUInt16LE(0, 34);
        central.writeUInt16LE(0, 36);
        central.writeUInt32LE(0, 38);
        central.writeUInt32LE(offset, 42);
        locals.push(local, name, body);
        centrals.push(central, name);
        offset += local.length + name.length + body.length;
    }
    const directory = Buffer.concat(centrals);
    const end = Buffer.alloc(22);
    end.writeUInt32LE(0x06054b50, 0);
    end.writeUInt16LE(centrals.length / 2, 8);
    end.writeUInt16LE(centrals.length / 2, 10);
    end.writeUInt32LE(directory.length, 12);
    end.writeUInt32LE(offset, 16);
    return Buffer.concat([...locals, directory, end]);
}

function writeVariant(name, target, store, vendor) {
    const manifest = JSON.parse(fs.readFileSync(path.join(source, 'manifest.json'), 'utf8'));
    manifest.version = version;
    const generated = variants[name](manifest, store);
    fs.rmSync(target, { recursive: true, force: true });
    copyTree(source, target);
    generated['takeover/page.js'] = takeoverBundle();
    for (const [file, content] of [...vendor, ...Object.entries(generated)]) {
        fs.mkdirSync(path.dirname(path.join(target, file)), { recursive: true });
        fs.writeFileSync(path.join(target, file), content);
    }
    fs.writeFileSync(path.join(target, 'manifest.json'), JSON.stringify(manifest, null, 4) + '\n');
}

const args = process.argv.slice(2);
let out = path.join(repository, 'artifacts', 'browser-extension');
const outIndex = args.indexOf('--out');
if (outIndex >= 0) {
    out = path.resolve(args[outIndex + 1]);
    args.splice(outIndex, 2);
}
const packageIndex = args.indexOf('--package');
const packaging = packageIndex >= 0;
if (packaging) {
    args.splice(packageIndex, 1);
}
const names = args.length ? args : Object.keys(variants);
const version = applicationVersion();
const vendor = await vendorFiles();
for (const name of names) {
    if (!variants[name]) {
        throw new Error(`Unknown browser "${name}"; use ${Object.keys(variants).join(' or ')}.`);
    }
    const target = path.join(out, name);
    writeVariant(name, target, false, vendor);
    console.log(`${name}: ${target}`);
    if (packaging) {
        const storeTarget = path.join(out, 'store', name);
        writeVariant(name, storeTarget, true, vendor);
        const archive = path.join(out, `LightPlayer-BrowserExtension-${name}-${version}.zip`);
        fs.writeFileSync(archive, zipFolder(storeTarget));
        console.log(`${name} store build: ${storeTarget}, ${archive}`);
    }
}
