using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace LightStudio.LightPlayer.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class BuildInfoGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var versions = context.AnalyzerConfigOptionsProvider
            .Select((options, _) => options.GlobalOptions.TryGetValue("build_property.BuildSourceVersion", out var version)
                ? version
                : null);

        context.RegisterSourceOutput(versions, (productionContext, version) =>
        {
            if (string.IsNullOrEmpty(version))
            {
                return;
            }

            var sourceVersion = Regex.Replace(version!, "[^A-Za-z0-9._+-]", "-");
            var source = """
                // <auto-generated />

                namespace LightStudio.LightPlayer;

                internal static class BuildInfo
                {
                    public const string SourceVersion =
                """ + " " + SymbolDisplay.FormatLiteral(sourceVersion, quote: true) + ";\n}\n";
            productionContext.AddSource("BuildInfo.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }
}